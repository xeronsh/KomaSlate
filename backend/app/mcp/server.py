class McpProtocolError(Exception):
    def __init__(self, code: int, message: str, data: Any = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.data = data


def _json_result(data: Any) -> dict[str, Any]:
    return {
        "content": [
            {
                "type": "text",
                "text": json.dumps(data, ensure_ascii=False, default=str),
            }
        ],
        "structuredContent": data,
    }


def _json_tool_error(code: str, message: str, details: dict[str, Any] | None = None) -> dict[str, Any]:
    payload = {"error": {"code": code, "message": message, "details": details or {}}}
    return {
        "isError": True,
        "content": [{"type": "text", "text": json.dumps(payload, ensure_ascii=False)}],
        "structuredContent": payload,
    }


async def _read_resource(
    uri: str,
    *,
    readonly_session_maker: Callable[[], Any] = async_readonly_session_maker,
) -> dict[str, Any]:
    project_match = re.fullmatch(r"komaslate://projects/(\d+)", uri)
    run_match = re.fullmatch(r"komaslate://runs/(\d+)", uri)
    node_match = re.fullmatch(r"komaslate://nodes/(shot|character)/(\d+)", uri)
    gate_match = re.fullmatch(r"komaslate://gates/(\d+)", uri)

    async with readonly_session_maker() as session:
        if project_match:
            pid = int(project_match.group(1))
            project = await session.get(Project, pid)
            if project is None:
                raise McpProtocolError(-32004, f"Project {pid} not found")
            data = {
                "id": project.id,
                "revision": project.revision,
                "title": project.title,
                "story": project.story,
                "style": project.style,
                "status": project.status,
                "summary": project.summary,
                "story_outline": project.story_outline,
                "visual_bible": project.visual_bible,
                "outline_approved": bool(project.outline_approved),
                "video_url": project.video_url,
            }
            return {"contents": [{"uri": uri, "mimeType": "application/json", "text": json.dumps(data, ensure_ascii=False, default=str)}]}

        if run_match:
            rid = int(run_match.group(1))
            run = await session.get(AgentRun, rid)
            if run is None:
                raise McpProtocolError(-32004, f"Run {rid} not found")
            checkpoints: list[dict[str, Any]] = []
            try:
                cp_rows = await session.execute(
                    text("SELECT stage, state_json, updated_at FROM engine_checkpoints WHERE run_id = :rid"),
                    {"rid": rid},
                )
                for stage, state_json, updated_at in cp_rows.all():
                    checkpoints.append(
                        {"stage": stage, "state": json.loads(state_json), "updated_at": updated_at}
                    )
            except Exception:
                checkpoints = []
            data = {
                "id": run.id,
                "revision": run.revision,
                "project_id": run.project_id,
                "status": run.status,
                "current_agent": run.current_agent,
                "progress": run.progress,
                "error": run.error,
                "awaiting_payload": run.awaiting_payload,
                "gate_feedback": run.gate_feedback,
                "checkpoints": checkpoints,
            }
            return {"contents": [{"uri": uri, "mimeType": "application/json", "text": json.dumps(data, ensure_ascii=False, default=str)}]}

        if node_match:
            kind, raw_id = node_match.group(1), int(node_match.group(2))
            if kind == "shot":
                shot = await session.get(Shot, raw_id)
                if shot is None:
                    raise McpProtocolError(-32004, f"Shot {raw_id} not found")
                data = {
                    "kind": "shot",
                    "id": shot.id,
                    "revision": shot.revision,
                    "project_id": shot.project_id,
                    "order": shot.order,
                    "description": shot.description,
                    "prompt": shot.prompt,
                    "image_prompt": shot.image_prompt,
                    "image_url": shot.image_url,
                    "video_url": shot.video_url,
                    "dialogue": shot.dialogue,
                    "camera": shot.camera,
                    "review_status": shot.review_status,
                }
            else:
                char = await session.get(Character, raw_id)
                if char is None:
                    raise McpProtocolError(-32004, f"Character {raw_id} not found")
                data = {
                    "kind": "character",
                    "id": char.id,
                    "revision": char.revision,
                    "project_id": char.project_id,
                    "name": char.name,
                    "description": char.description,
                    "visual_notes": char.visual_notes,
                    "image_url": char.image_url,
                }
            return {"contents": [{"uri": uri, "mimeType": "application/json", "text": json.dumps(data, ensure_ascii=False, default=str)}]}

        if gate_match:
            rid = int(gate_match.group(1))
            run = await session.get(AgentRun, rid)
            if run is None:
                raise McpProtocolError(-32004, f"Run {rid} not found")
            data = {
                "run_id": run.id,
                "revision": run.revision,
                "project_id": run.project_id,
                "status": run.status,
                "waiting_for_approval": run.status == "waiting_for_approval",
                "human_only": True,
                "awaiting_payload": run.awaiting_payload,
                "gate_feedback": run.gate_feedback,
            }
            return {"contents": [{"uri": uri, "mimeType": "application/json", "text": json.dumps(data, ensure_ascii=False, default=str)}]}

    raise McpProtocolError(-32602, f"Unsupported resource URI: {uri}")


async def _call_tool(
    name: str,
    arguments: dict[str, Any],
    *,
    session_maker: Callable[[], Any] = async_session_maker,
    readonly_session_maker: Callable[[], Any] = async_readonly_session_maker,
) -> dict[str, Any]:
    settings = get_settings()

    if name == "inspect_project":
        project_id = int(arguments["project_id"])
        async with readonly_session_maker() as session:
            project = await session.get(Project, project_id)
            if project is None:
                return _json_tool_error("NOT_FOUND", f"Project {project_id} not found")
            chars = (
                await session.execute(select(Character).where(Character.project_id == project_id))
            ).scalars().all()
            shots = (
                await session.execute(
                    select(Shot).where(Shot.project_id == project_id).order_by(Shot.order.asc())
                )
            ).scalars().all()
            runs = (
                await session.execute(
                    select(AgentRun)
                    .where(AgentRun.project_id == project_id)
                    .order_by(AgentRun.id.desc())
                    .limit(1)
                )
            ).scalars().all()
            latest_run = runs[0] if runs else None
            return _json_result(
                {
                    "project": {
                        "id": project.id,
                        "revision": project.revision,
                        "title": project.title,
                        "status": project.status,
                        "style": project.style,
                        "visual_bible": project.visual_bible,
                    },
                    "characters": [
                        {"id": c.id, "revision": c.revision, "name": c.name, "image_url": c.image_url}
                        for c in chars
                    ],
                    "shots": [
                        {
                            "id": s.id,
                            "revision": s.revision,
                            "order": s.order,
                            "description": s.description,
                            "review_status": s.review_status,
                            "image_url": s.image_url,
                            "video_url": s.video_url,
                        }
                        for s in shots
                    ],
                    "latest_run": (
                        {
                            "id": latest_run.id,
                            "revision": latest_run.revision,
                            "status": latest_run.status,
                            "current_agent": latest_run.current_agent,
                            "progress": latest_run.progress,
                        }
                        if latest_run
                        else None
                    ),
                }
            )

    if name == "trigger_run":
        project_id = int(arguments["project_id"])
        stage = str(arguments.get("stage") or "full")
        auto_mode = bool(arguments.get("auto_mode", False))
        try:
            await ensure_engine_running(settings.engine_url, settings.database_url, STATIC_DIR)
        except EngineUnavailableError as exc:
            return _json_tool_error("ENGINE_UNAVAILABLE", str(exc))

        async with session_maker() as session:
            project = await session.get(Project, project_id)
            if project is None:
                return _json_tool_error("NOT_FOUND", f"Project {project_id} not found")
            active = (
                await session.execute(
                    select(AgentRun.id)
                    .where(AgentRun.project_id == project_id)
                    .where(AgentRun.status.in_(("queued", "running", "waiting_for_approval")))
                    .limit(1)
                )
            ).first()
            if active is not None:
                return _json_tool_error("RUN_ALREADY_ACTIVE", f"Project {project_id} already has an active run")
            from app.services.provider_resolution import resolve_project_provider_settings_async

            resolution = await resolve_project_provider_settings_async(project, settings)
            if not resolution.valid:
                return _json_tool_error("PROVIDER_PRECHECK_FAILED", "Provider configuration is invalid")
            previous_version = await capture_project_version(session, project_id)
            ctx = await build_run_context_snapshot(
                session=session, settings=settings, project=project, provider_resolution=resolution
            )
            run = AgentRun(
                project_id=project_id,
                status="queued",
                current_agent="orchestrator",
                progress=0.0,
                provider_snapshot=resolution.as_project_provider_settings().model_dump(mode="json"),
                workflow_version=WORKFLOW_VERSION,
                context_snapshot={
                    **ctx,
                    **({"previous_version": previous_version} if previous_version else {}),
                    "execution_command": {
                        "version": 1,
                        "stage": stage,
                        "auto_mode": auto_mode,
                        "user_feedback": "",
                        "target_character_ids": [],
                        "target_shot_ids": [],
                    },
                },
            )
            session.add(run)
            await session.commit()
            await session.refresh(run)
            assert run.id is not None
            run_id = run.id
            try:
                await engine_start_run(
                    settings.engine_url,
                    project_id=project_id,
                    run_id=run_id,
                    stage=stage,
                    auto_mode=auto_mode,
                )
            except (EngineUnavailableError, EngineConflictError) as exc:
                run.status = "failed"
                run.error = str(exc)
                session.add(run)
                await session.commit()
                return _json_tool_error("ENGINE_DISPATCH_FAILED", str(exc))
            return _json_result({"run_id": run_id, "project_id": project_id, "status": "queued", "stage": stage})

    if name == "resume_run":
        run_id = int(arguments["run_id"])
        async with readonly_session_maker() as session:
            run = await session.get(AgentRun, run_id)
            if run is None:
                return _json_tool_error("RUN_NOT_FOUND", f"Run {run_id} not found")
            if run.status in ("succeeded", "cancelled"):
                return _json_tool_error("RUN_NOT_RESUMABLE", f"Run {run_id} is {run.status}")
            project_id = run.project_id
        try:
            await ensure_engine_running(settings.engine_url, settings.database_url, STATIC_DIR)
            res = await engine_resume_run(settings.engine_url, project_id=project_id, run_id=run_id)
            return _json_result({"run_id": run_id, "project_id": project_id, "engine": res})
        except (EngineUnavailableError, EngineConflictError) as exc:
            return _json_tool_error("ENGINE_UNAVAILABLE", str(exc))

    if name == "cancel_run":
        run_id = int(arguments["run_id"])
        async with session_maker() as session:
            run = await session.get(AgentRun, run_id)
            if run is None:
                return _json_tool_error("RUN_NOT_FOUND", f"Run {run_id} not found")
            if run.status in ("succeeded", "cancelled"):
                return _json_result({"run_id": run_id, "status": run.status})
            from app.db.utils import utcnow

            run.cancel_requested_at = utcnow()
            run.status = "cancelling"
            session.add(run)
            await commit_versioned(session, run, entity="agentrun")
        try:
            await engine_cancel_run(settings.engine_url, run_id)
        except EngineUnavailableError:
            pass
        return _json_result({"run_id": run_id, "status": "cancelling"})

    if name == "submit_gate_feedback":
        run_id = int(arguments["run_id"])
        feedback_text = str(arguments.get("feedback") or "").strip()
        if not feedback_text:
            return _json_tool_error("VALIDATION_ERROR", "feedback cannot be blank")
        async with readonly_session_maker() as session:
            run = await session.get(AgentRun, run_id)
            if run is None:
                return _json_tool_error("RUN_NOT_FOUND", f"Run {run_id} not found")
            project_id = run.project_id
        try:
            fb = await submit_gate_feedback(run_id, project_id=project_id, content=feedback_text)
            return _json_result({"run_id": run_id, "feedback_id": fb["id"], "round": fb.get("round")})
        except (GateFeedbackRejected, ConflictError) as exc:
            return _json_tool_error(getattr(exc, "code", "GATE_REJECTED"), str(exc))

    if name == "submit_gate_approval":
        run_id = int(arguments["run_id"])
        human_auth_token = arguments.get("human_auth_token")
        async with session_maker() as session:
            run = await session.get(AgentRun, run_id)
            if run is None:
                return _json_tool_error("RUN_NOT_FOUND", f"Run {run_id} not found")
            project_id = run.project_id
            authorized = await consume_human_auth_token(
                session,
                run_id=run_id,
                token=human_auth_token if isinstance(human_auth_token, str) else None,
            )
        if not authorized:
            return _json_tool_error(
                "INVALID_HUMAN_AUTH_TOKEN",
                "Human authorization token is missing, expired (60s TTL), already used, or mismatched for this run.",
            )
        try:
            await approve_gate(run_id, project_id=project_id)
            return _json_result({"run_id": run_id, "status": "accepted"})
        except (GateFeedbackRejected, ConflictError) as exc:
            return _json_tool_error(getattr(exc, "code", "GATE_REJECTED"), str(exc))

    if name == "update_shot":
        shot_id = int(arguments["shot_id"])
        fields = arguments.get("fields")
        expected_revision = arguments.get("expected_revision")
        if not isinstance(fields, dict):
            return _json_tool_error("VALIDATION_ERROR", "fields must be an object")
        if not isinstance(expected_revision, int) or expected_revision < 1:
            return _json_tool_error("VALIDATION_ERROR", "expected_revision (>= 1) is required")
        async with session_maker() as session:
            shot = await session.get(Shot, shot_id)
            if shot is None:
                return _json_tool_error("NOT_FOUND", f"Shot {shot_id} not found")
            try:
                assert_expected_revision(shot, expected_revision, entity="shot")
                for key, val in fields.items():
                    if key in _UPDATABLE_SHOT_FIELDS:
                        setattr(shot, key, val)
                session.add(shot)
                await session.flush()
                from app.schemas.project import ShotRead

                shot_data = ShotRead.model_validate(shot).model_dump(mode="json")
                await emit_project_event(
                    session,
                    project_id=shot.project_id,
                    event_type="shot_updated",
                    payload={"shot": shot_data},
                )
                await commit_versioned(session, shot, entity="shot")
                return _json_result({"shot": shot_data})
            except ConflictError as exc:
                await session.rollback()
                return _json_tool_error(exc.code, exc.message, exc.details)

    raise McpProtocolError(-32601, f"Unknown tool: {name}")


async def handle_jsonrpc_message(
    message: dict[str, Any],
    *,
    session_maker: Callable[[], Any] = async_session_maker,
    readonly_session_maker: Callable[[], Any] = async_readonly_session_maker,
) -> dict[str, Any] | None:
    """Process one MCP JSON-RPC 2.0 request or notification."""
    if not isinstance(message, dict) or message.get("jsonrpc") != "2.0":
        return {
            "jsonrpc": "2.0",
            "id": message.get("id") if isinstance(message, dict) else None,
            "error": {"code": -32600, "message": "Invalid Request"},
        }

    req_id = message.get("id")
    method = message.get("method")
    params = message.get("params") if isinstance(message.get("params"), dict) else {}

    # Notifications have no id -> no reply
    if req_id is None:
        return None

    try:
        if method == "initialize":
            result: Any = {
                "protocolVersion": MCP_PROTOCOL_VERSION,
                "capabilities": {
                    "resources": {"subscribe": False, "listChanged": False},
                    "tools": {"listChanged": False},
                },
                "serverInfo": SERVER_INFO,
            }
        elif method == "ping":
            result = {}
        elif method == "resources/list":
            result = {"resources": []}
        elif method == "resources/templates/list":
            result = {"resourceTemplates": _RESOURCE_TEMPLATES}
        elif method == "resources/read":
            uri = params.get("uri")
            if not isinstance(uri, str) or not uri:
                raise McpProtocolError(-32602, "uri is required")
            result = await _read_resource(uri, readonly_session_maker=readonly_session_maker)
        elif method == "tools/list":
            result = {"tools": _TOOLS}
        elif method == "tools/call":
            tool_name = params.get("name")
            arguments = params.get("arguments")
            if not isinstance(tool_name, str) or not tool_name:
                raise McpProtocolError(-32602, "tool name is required")
            if arguments is None:
                arguments = {}
            if not isinstance(arguments, dict):
                raise McpProtocolError(-32602, "arguments must be an object")
            result = await _call_tool(
                tool_name,
                arguments,
                session_maker=session_maker,
                readonly_session_maker=readonly_session_maker,
            )
        else:
            raise McpProtocolError(-32601, f"Method not found: {method}")

        return {"jsonrpc": "2.0", "id": req_id, "result": result}
    except McpProtocolError as exc:
        err: dict[str, Any] = {"code": exc.code, "message": exc.message}
        if exc.data is not None:
            err["data"] = exc.data
        return {"jsonrpc": "2.0", "id": req_id, "error": err}
    except Exception as exc:  # noqa: BLE001
        logger.exception("Unhandled MCP request failure")
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "error": {"code": -32603, "message": str(exc)},
        }


def _protocol_stdout() -> TextIO:
    sys.stdout.flush()
    protocol = os.fdopen(os.dup(1), "w", buffering=1, encoding="utf-8")
    os.dup2(2, 1)
    sys.stdout = sys.stderr
    return protocol


async def _serve_stdio(out: TextIO) -> None:
    loop = asyncio.get_running_loop()
    while True:
        line = await loop.run_in_executor(None, sys.stdin.readline)
        if not line:
            break
        raw = line.strip()
        if not raw:
            continue
        try:
            msg = json.loads(raw)
        except json.JSONDecodeError:
            resp = {
                "jsonrpc": "2.0",
                "id": None,
                "error": {"code": -32700, "message": "Parse error"},
            }
        else:
            resp = await handle_jsonrpc_message(msg)
        if resp is not None:
            out.write(json.dumps(resp, ensure_ascii=False) + "\n")
            out.flush()


def run_mcp_stdio() -> None:
    out = _protocol_stdout()
    asyncio.run(_serve_stdio(out))


def create_mcp_http_app() -> FastAPI:
    mcp_app = FastAPI(title="KomaSlate Inbound MCP Server", version="0.1.0")

    @mcp_app.get("/health")
    async def mcp_health() -> dict[str, str]:
        return {"status": "ok", "server": SERVER_INFO["name"]}

    @mcp_app.post("/mcp")
    async def mcp_endpoint(request: Request) -> JSONResponse:
        try:
            body = await request.json()
        except Exception:
            return JSONResponse(
                status_code=400,
                content={"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": "Parse error"}},
            )
        if isinstance(body, list):
            responses = []
            for item in body:
                res = await handle_jsonrpc_message(item)
                if res is not None:
                    responses.append(res)
            return JSONResponse(status_code=200, content=responses)
        res = await handle_jsonrpc_message(body)
        if res is None:
            return JSONResponse(status_code=202, content={})
        return JSONResponse(status_code=200, content=res)

    return mcp_app


def run_mcp_http(host: str = "127.0.0.1", port: int = 18768) -> None:
    import uvicorn

    uvicorn.run(create_mcp_http_app(), host=host, port=port, log_level="info")
