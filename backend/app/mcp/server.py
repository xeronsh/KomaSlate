"""Inbound MCP Server for KomaSlate (Northbound Gateway Adapter).

Strictly adheres to AGENTS.md invariants:
- Zero orchestration: never advances or decides workflow stages itself.
- Human-only approval gates: `approve_gate` is excluded; `submit_gate_approval`
  requires a 60s single-use `human_auth_token` generated by a human UI/CLI action.
- CAS concurrency: `update_shot` enforces `expected_revision`.
"""

